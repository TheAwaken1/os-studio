const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs');
const root = path.resolve(__dirname, '..');
(async () => {
  const start = require(path.join(root, 'start.js'));
  assert.equal(start.daemon, true);
  const shell = start.run.find(s => s.method === 'shell.run');
  assert.equal(shell.params.path, 'app');
  assert.equal(shell.params.venv, 'env');
  assert(shell.params.message.some(s => s.includes('--no-browser')));
  const capture = start.run.find(s => s.method === 'local.set');
  assert.equal(capture.params.url, '{{input.event[1]}}');
  const event = shell.params.on[0].event;
  const match = new RegExp(event.slice(1, -1)).exec('YuE2 Song Studio -> http://127.0.0.1:42001');
  assert.equal(match[1], 'http://127.0.0.1:42001');
  assert(start.run.some(s => s.method === 'process.wait'));
  const install = require(path.join(root, 'install.js'));
  assert.equal(install.requires.bundle, 'ai');
  assert(install.run.some(s => s.when === "{{!which('ffmpeg')}}" && JSON.stringify(s).includes('conda install -c conda-forge ffmpeg -y')));
  assert(JSON.stringify(install).includes('whisperx==3.8.6 --no-deps'));
  assert(JSON.stringify(install).includes('--python 3.10'));
  const reset = require(path.join(root, 'reset.js'));
  assert(reset.run.filter(s => s.method === 'fs.rm').every(s => ['app/env', 'app/.installed.json'].includes(s.params.path)));
  const menu = require(path.join(root, 'pinokio.js'));
  const info = (installed, running, url) => ({exists:p => installed, running:p => p === running, local:p => ({url})});
  assert.equal((await menu.menu({}, info(false)))[0].href, 'install.js');
  assert.equal((await menu.menu({}, info(true)))[0].href, 'start.js');
  assert.equal((await menu.menu({}, info(true,'start.js','http://127.0.0.1:1234')))[0].href, 'http://127.0.0.1:1234');
  assert.equal((await menu.menu({}, info(true,'install.js')))[0].text, 'Installing');
  for (const name of ['pinokio.json','README.md','icon.svg','tools/configure.py']) assert(fs.existsSync(path.join(root,name)), name);
  console.log('PASS: launcher lifecycle contracts, menu states, safe reset, metadata');
})().catch(e => {console.error(e); process.exit(1)});
